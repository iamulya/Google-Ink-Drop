export function getInjectionPoints(numberStr: string): { x: number, y: number }[] {
  const bitmap = numberBitmaps[numberStr];
  if (!bitmap) return [];
  
  const points: { x: number, y: number }[] = [];
  const height = bitmap.length;
  const width = bitmap[0].length;
  
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (bitmap[y][x] === '#') {
        // Normalize to 0-1, centered
        const nx = (x / width) - 0.5;
        // Invert Y as bitmap 0 is top, WebGL 0 is bottom
        const ny = 0.5 - (y / height);
        
        // We'll scale these in the WebGL code relative to aspect ratio 
        // to be about 60% of viewport height
        points.push({ x: nx, y: ny });
      }
    }
  }
  
  return points;
}
